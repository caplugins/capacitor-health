#!/usr/bin/env node
// Writes registry/catalogs/workout-activity-types.md: every HKWorkoutActivityType case (from the SDK
// header, with its raw value and minimum iOS) and every Health Connect ExerciseSessionRecord /
// ExerciseSegment constant (from the connect-client jar, through javap). T40's activity map is
// checked against it.
//
//   node scripts/workout-catalog.mjs <HealthKit.framework/Headers> <connect-client runtime jar>
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { ROOT } from './lib/registry.mjs';

const [headers, jar] = process.argv.slice(2);
if (!headers || !jar) {
  console.error('usage: node scripts/workout-catalog.mjs <HealthKit Headers dir> <connect-client runtime jar>');
  process.exit(1);
}

function healthKitCases() {
  const source = readFileSync(join(headers, 'HKWorkoutActivityType.h'), 'utf8');
  const body = source.slice(source.indexOf('typedef NS_ENUM(NSUInteger, HKWorkoutActivityType)'));
  const cases = [];
  for (const line of body.slice(0, body.indexOf('};')).split('\n')) {
    const m = line.match(/^\s*HKWorkoutActivityType(\w+)\s*(.*?)=\s*(\d+),?/);
    if (!m) continue;
    const [, name, attributes, raw] = m;
    let note = '';
    let ios = '8.0';
    if (/API_UNAVAILABLE/.test(attributes)) note = 'unavailable';
    else if (/API_DEPRECATED/.test(attributes)) note = `deprecated ${attributes.match(/ios\(([\d.]+), ([\d.]+)\)/)?.[2] ?? ''}`.trim();
    const available = attributes.match(/API_AVAILABLE\(ios\(([\d.]+)\)/);
    if (available) ios = available[1];
    cases.push({ name, raw: Number(raw), ios, note });
  }
  return cases;
}

function healthConnectConstants(cls, prefix) {
  const out = execFileSync(process.env.JAVAP ?? 'javap', ['-constants', '-cp', jar, `androidx.health.connect.client.records.${cls}`], {
    encoding: 'utf8',
  });
  return [...out.matchAll(new RegExp(`static final int (${prefix}\\w+) = (\\d+);`, 'g'))].map(([, name, raw]) => ({
    name,
    raw: Number(raw),
  }));
}

const hk = healthKitCases();
const exercise = healthConnectConstants('ExerciseSessionRecord', 'EXERCISE_TYPE_');
const segments = healthConnectConstants('ExerciseSegment', 'EXERCISE_SEGMENT_TYPE_');

const md = `# Workout activity types (reference)

Generated by \`scripts/workout-catalog.mjs\` from the iOS ${process.env.SDK_VERSION ?? '27.0'} SDK's \`HKWorkoutActivityType.h\` and
\`connect-client\` 1.1.0. Do not edit by hand. The unified activity map is in
[04-type-mapping.md §4b](../04-type-mapping.md#4b-workout-activity-types) and \`registry/types.json\`.

## HKWorkoutActivityType

| Case | Raw | iOS | Notes |
|---|---|---|---|
${hk.map((c) => `| \`${c.name}\` | ${c.raw} | ${c.ios} | ${c.note} |`).join('\n')}

## ExerciseSessionRecord exercise types

| Constant | Value |
|---|---|
${exercise.map((c) => `| \`${c.name}\` | ${c.raw} |`).join('\n')}

## ExerciseSegment segment types

| Constant | Value |
|---|---|
${segments.map((c) => `| \`${c.name}\` | ${c.raw} |`).join('\n')}
`;

writeFileSync(join(ROOT, 'registry/catalogs/workout-activity-types.md'), md);
console.log(`${hk.length} HealthKit cases, ${exercise.length} exercise types, ${segments.length} segment types`);
